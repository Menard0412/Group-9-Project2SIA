/**
 * Permanently deletes the signed-in account. Instructors' uploaded class files are removed from
 * storage first, because deleting the account only removes database rows.
 */
export async function deleteMyAccount(userId: string): Promise<void> {
  const classes = await listClasses();
  for (const room of classes.filter((c) => c.instructorId === userId)) {
    await removeAllMaterialFiles(room.id);
  }
  const { error } = await supabase.rpc('delete_my_account');
  fail(error);
  // The login no longer exists, so just clear it from this device.
  await supabase.auth.signOut({ scope: 'local' }).catch(() => undefined);
}
