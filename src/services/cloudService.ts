import { supabase } from '../lib/supabase';
import { removeAllMaterialFiles } from './classworkService';
import type {
  AdminProfile,
  Announcement,
  ClassRoom,
  InstructorStatus,
  Member,
  Post,
  Profile,
  UserRole,
} from '../types/cloud';

type Row = Record<string, unknown>;

const str = (value: unknown, fallback = ''): string => (typeof value === 'string' ? value : fallback);
const asRole = (value: unknown): UserRole =>
  value === 'admin' || value === 'instructor' ? value : 'learner';

const asStatus = (value: unknown): InstructorStatus =>
  value === 'pending' || value === 'approved' || value === 'rejected' ? value : 'none';

function rowOf(value: unknown): Row | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value) ? (value as Row) : null;
}

function rowsOf(value: unknown): Row[] {
  if (!Array.isArray(value)) return [];
  return value.filter((r): r is Row => typeof r === 'object' && r !== null);
}

/** Embedded relations can come back as an object or a one-item array. */
function embedded(value: unknown): Row | null {
  return rowOf(Array.isArray(value) ? value[0] : value);
}

function fail(error: { message: string } | null): void {
  if (error) throw new Error(error.message);
}

const CLASS_COLUMNS =
  'id, instructor_id, title, description, join_code, created_at, instructor:profiles!instructor_id(display_name)';

function mapClass(row: Row): ClassRoom {
  return {
    id: str(row.id),
    instructorId: str(row.instructor_id),
    instructorName: str(embedded(row.instructor)?.display_name, 'Instructor'),
    title: str(row.title),
    description: str(row.description),
    joinCode: str(row.join_code),
    createdAt: str(row.created_at),
  };
}

export async function fetchProfile(userId: string): Promise<Profile | null> {
  const { data, error } = await supabase
    .from('profiles')
    .select('id, display_name, role, instructor_status')
    .eq('id', userId)
    .maybeSingle();
  fail(error);
  const row = rowOf(data);
  if (!row) return null;
  return {
    id: str(row.id),
    displayName: str(row.display_name, 'User'),
    role: asRole(row.role),
    instructorStatus: asStatus(row.instructor_status),
  };
}

/** Every class the signed-in user teaches or is enrolled in (row level security does the filtering). */
export async function listClasses(): Promise<ClassRoom[]> {
  const { data, error } = await supabase
    .from('classes')
    .select(CLASS_COLUMNS)
    .order('created_at', { ascending: false });
  fail(error);
  return rowsOf(data).map(mapClass);
}

export async function getClass(id: string): Promise<ClassRoom | null> {
  const { data, error } = await supabase.from('classes').select(CLASS_COLUMNS).eq('id', id).maybeSingle();
  fail(error);
  const row = rowOf(data);
  return row ? mapClass(row) : null;
}

export async function createClass(instructorId: string, title: string, description: string): Promise<string> {
  // The join code is generated by the database; retry in the rare case of a collision.
  for (let attempt = 0; attempt < 3; attempt += 1) {
    const { data, error } = await supabase
      .from('classes')
      .insert({ instructor_id: instructorId, title: title.trim(), description: description.trim() })
      .select('id')
      .single();
    if (!error) return str(rowOf(data)?.id);
    if (error.code !== '23505') throw new Error(error.message);
  }
  throw new Error('Could not generate a unique join code. Please try again.');
}

export async function joinClass(code: string): Promise<string> {
  const { data, error } = await supabase.rpc('join_class', { code });
  fail(error);
  return typeof data === 'string' ? data : '';
}

export async function deleteClass(id: string): Promise<void> {
  const { error } = await supabase.from('classes').delete().eq('id', id);
  fail(error);
}

export async function leaveClass(classId: string, learnerId: string): Promise<void> {
  const { error } = await supabase.from('enrollments').delete().eq('class_id', classId).eq('learner_id', learnerId);
  fail(error);
}

export async function listAnnouncements(classId: string): Promise<Announcement[]> {
  const { data, error } = await supabase
    .from('announcements')
    .select('id, class_id, author_id, title, body, created_at, author:profiles!author_id(display_name)')
    .eq('class_id', classId)
    .order('created_at', { ascending: false });
  fail(error);
  return rowsOf(data).map((row) => ({
    id: str(row.id),
    classId: str(row.class_id),
    authorId: str(row.author_id),
    authorName: str(embedded(row.author)?.display_name, 'Instructor'),
    title: str(row.title),
    body: str(row.body),
    createdAt: str(row.created_at),
  }));
}

