export async function listPosts(classId: string): Promise<Post[]> {
  const { data, error } = await supabase
    .from('posts')
    .select('id, class_id, author_id, body, created_at, author:profiles!author_id(display_name, role)')
    .eq('class_id', classId)
    .order('created_at', { ascending: false });
  fail(error);
  return rowsOf(data).map((row) => {
    const author = embedded(row.author);
    return {
      id: str(row.id),
      classId: str(row.class_id),
      authorId: str(row.author_id),
      authorName: str(author?.display_name, 'Unknown'),
      authorRole: asRole(author?.role),
      body: str(row.body),
      createdAt: str(row.created_at),
    };
  });
}

